from pathlib import Path
from collections import Counter
import json
import re
from xml.sax.saxutils import escape

root = Path(__file__).resolve().parents[1]
entries = json.loads((root / 'translations/extra.json').read_text(encoding='utf-8'))
translated = {}
for line in (root / 'translations/extra-zh-fa.psv').read_text(encoding='utf-8-sig').splitlines():
    key, zh, fa = line.split('|', 2)
    assert key not in translated, f'Duplicate translation key: {key}'
    translated[key] = {'zh': zh.replace(r'\n', '\n'), 'fa': fa.replace(r'\n', '\n')}
assert entries.keys() == translated.keys(), 'Translation keys differ from extra.json'
assert len({entry['en'] for entry in entries.values()}) == len(entries), 'Duplicate English lookup key'

format_token = re.compile(r'%(?:(\d+)\$)?[-#+0,(]*\d*(?:\.(\d+))?([dsf%])')
def format_signature(value):
    sequential = 0
    result = Counter()
    for token in format_token.finditer(value):
        position, precision, conversion = token.groups()
        if conversion == '%':
            result['literal-percent'] += 1
            continue
        if position is None:
            sequential += 1
            position = str(sequential)
        result[(position, precision, conversion)] += 1
    return result

for key, entry in entries.items():
    expected = format_signature(entry['en'])
    for language, value in (entry | translated[key]).items():
        assert value.strip(), f'Empty translation: {key}/{language}'
        assert expected == format_signature(value), f'Format arguments differ: {key}/{language}'

def android_xml(value):
    escaped = escape(value).replace("'", r"\'").replace('"', r'\"').replace('\n', r'\n')
    # Android otherwise trims the spaces used by labels concatenated with a value.
    return '"' + escaped + '"' if value != value.strip() else escaped
for language, folder in [('en', 'values'), ('en', 'values-en'), ('ru', 'values-ru'), ('zh', 'values-b+zh+Hans'), ('fa', 'values-fa')]:
    path = root / 'app/src/main/res' / folder / 'extra_strings.xml'
    path.write_text('<?xml version="1.0" encoding="utf-8"?>\n<resources>\n' + ''.join(
        f'    <string name="{key}" formatted="false">' + android_xml((value | translated[key])[language]) + '</string>\n'
        for key, value in entries.items()) + '</resources>\n', encoding='utf-8')
path = root / 'app/src/main/java/com/danieldk/splatevpn/ui/theme/ExtraStrings.kt'
path.write_text('''// Generated by scripts/sync_extra_translations.py.
package com.danieldk.splatevpn.ui.theme

import com.danieldk.splatevpn.R

internal fun AppStrings.localized(ru: String, en: String): String {
    if (this is RussianAppStrings) return ru
    if (this !is ResourceAppStrings) return en
    val id = when (en) {
''' + ''.join(f'        {json.dumps(value["en"], ensure_ascii=False)} -> R.string.{key}\n' for key, value in entries.items()) + '''        else -> return en
    }
    return resources.getString(id)
}
''', encoding='utf-8')
print(f'Validated {len(entries)} additional translations.')
